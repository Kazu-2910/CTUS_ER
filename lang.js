// 4. BỘ MÁY DỊCH TỰ ĐỘNG TOÀN TRANG (DOM + TEXT NODE + CHART.JS + ALERT/CONFIRM)
let currentLang = localStorage.getItem('srl_lang') || 'vi';
let isTranslating = false;
const origTextMap = new WeakMap();
const lastTranslatedMap = new WeakMap();

/**
 * Lấy chuỗi động theo key (dùng cho thông báo nhắc lịch...)
 */
function t(key, params = {}) {
    let text = (SRL_DYNAMIC[currentLang] && SRL_DYNAMIC[currentLang][key])
        || (SRL_DYNAMIC.vi && SRL_DYNAMIC.vi[key])
        || key;
    Object.keys(params).forEach(k => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    });
    return text;
}

function translateString(str, lang) {
    if (!str || lang === 'vi') return str;
    const dict = SRL_DICT[lang];
    const trimmed = str.trim();
    if (!trimmed) return str;

    // 1. Khớp chính xác trong từ điển
    if (dict && dict[trimmed]) {
        return str.replace(trimmed, dict[trimmed]);
    }

    // 2. Khớp theo quy tắc Regex (cho Học kỳ, Ngày, Điểm, Tiến độ...)
    const patterns = SRL_PATTERNS[lang];
    if (patterns) {
        let out = trimmed;
        let changed = false;
        for (const [regex, replacement] of patterns) {
            const next = out.replace(regex, replacement);
            if (next !== out) {
                out = next;
                changed = true;
            }
        }
        if (changed) {
            return str.replace(trimmed, out);
        }
    }

    return str;
}

function translateSingleTextNode(node, lang) {
    if (!node || node.nodeType !== 3) return;
    const parent = node.parentElement;
    if (!parent) return;
    const tag = parent.tagName;
    if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(tag)) return;
    if (parent.closest('#lang-selector, #lang-selector-home, #admin-theme-select, .monthly-theme-item select')) return;
    if (!node.nodeValue || !node.nodeValue.trim()) return;

    if (!origTextMap.has(node)) {
        origTextMap.set(node, node.nodeValue);
    }
    const original = origTextMap.get(node);
    const target = lang === 'vi' ? original : translateString(original, lang);
    if (node.nodeValue !== target) {
        lastTranslatedMap.set(node, target);
        node.nodeValue = target;
    }
}

function translateNodeTree(root, lang) {
    if (!root) return;
    const prevFlag = isTranslating;
    isTranslating = true;

    try {
        if (root.nodeType === 3) {
            translateSingleTextNode(root, lang);
            return;
        }

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: (node) => {
                const parent = node.parentElement;
                if (!parent) return NodeFilter.FILTER_REJECT;
                const tag = parent.tagName;
                if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(tag)) return NodeFilter.FILTER_REJECT;
                if (parent.closest('#lang-selector, #lang-selector-home, #admin-theme-select, .monthly-theme-item select')) return NodeFilter.FILTER_REJECT;
                if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        });

        let node;
        while ((node = walker.nextNode())) {
            translateSingleTextNode(node, lang);
        }

        const elements = root.querySelectorAll ? root.querySelectorAll('[placeholder], [title]') : [];
        elements.forEach(el => {
            ['placeholder', 'title'].forEach(attr => {
                if (!el.hasAttribute(attr)) return;
                const origAttr = 'data-orig-' + attr;
                if (!el.hasAttribute(origAttr)) {
                    el.setAttribute(origAttr, el.getAttribute(attr));
                }
                const original = el.getAttribute(origAttr);
                const target = lang === 'vi' ? original : translateString(original, lang);
                if (el.getAttribute(attr) !== target) {
                    el.setAttribute(attr, target);
                }
            });
        });
    } finally {
        if (!prevFlag && typeof langObserver !== 'undefined') {
            langObserver.takeRecords();
        }
        isTranslating = prevFlag;
    }
}

// 5. DỊCH TỰ ĐỘNG CÁC BIỂU ĐỒ CHART.JS (Radar Chart & Line Chart)
function translateCharts(lang) {
    if (typeof Chart === 'undefined' || !Chart.getChart) return;

    ['radarChart', 'semesterLineChart'].forEach(canvasId => {
        const chart = Chart.getChart(canvasId);
        if (!chart) return;

        if (!chart._origLabels && Array.isArray(chart.data.labels)) {
            chart._origLabels = [...chart.data.labels];
        }
        if (chart._origLabels) {
            chart.data.labels = chart._origLabels.map(lbl =>
                lang === 'vi' ? lbl : translateString(String(lbl), lang)
            );
        }

        if (Array.isArray(chart.data.datasets)) {
            chart.data.datasets.forEach(ds => {
                if (ds.label !== undefined) {
                    if (ds._origLabel === undefined) ds._origLabel = ds.label;
                    ds.label = lang === 'vi' ? ds._origLabel : translateString(String(ds._origLabel), lang);
                }
            });
        }

        chart.update('none');
    });
}

